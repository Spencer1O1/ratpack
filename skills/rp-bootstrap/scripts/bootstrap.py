#!/usr/bin/env python3
"""Preview or add Ratpack starter files without overwriting project content."""

import argparse
import importlib.util
from pathlib import Path
import sys


SKILL = Path(__file__).resolve().parents[1]
SPEC = importlib.util.spec_from_file_location("ratpack_adoption", Path(__file__).with_name("adoption.py"))
adoption = importlib.util.module_from_spec(SPEC)
# Avoid creating bytecode files as a side effect of a read-only preview.
exec(compile(Path(SPEC.origin).read_bytes(), SPEC.origin, "exec"), adoption.__dict__)


def prepare(target, owner, source_revision=None):
    """Preflight every output, including parent paths, before any writes."""
    target = adoption.project_root(target)
    if not owner.strip():
        raise ValueError("An integration owner is required")
    revision, origin = adoption.source_provenance(SKILL, source_revision)
    outputs = adoption.render_outputs(SKILL, owner.strip())
    manifest = adoption.make_manifest(outputs, revision, origin)
    existing = adoption.load_manifest(target)
    if existing is not None:
        if existing["files"] != manifest["files"]:
            raise ValueError("Adopted baseline differs; use upgrade.py and reconcile manually")
        if source_revision is not None and existing["source_revision"] != revision:
            raise ValueError("Adopted provenance differs; reconcile manually")
        # Matching reruns preserve the original adoption record, including origin.
        outputs[adoption.LOCK] = (target / adoption.LOCK).read_bytes()
    else:
        if adoption.checked_path(target, "ratpack.json").exists():
            raise ValueError("Legacy adoption has no manifest; reconcile manually; baseline unknown")
        outputs[adoption.LOCK] = adoption.encode_json(manifest)
    pending = []
    for relative, content in sorted(outputs.items()):
        path = adoption.checked_path(target, relative)
        if path.exists():
            if not path.is_file() or path.read_bytes() != content:
                raise ValueError(
                    f"Existing content differs: {relative}; reconcile manually"
                )
        else:
            pending.append((path, content))
    return target, pending


def bootstrap(target, owner, apply=False, source_revision=None):
    target, pending = prepare(target, owner, source_revision)
    for path, content in pending:
        print(f"{'ADD' if apply else 'WOULD ADD'} {path.relative_to(target)}")
        if apply:
            path.parent.mkdir(parents=True, exist_ok=True)
            # Exclusive creation also prevents overwriting a concurrent writer.
            with path.open("xb") as handle:
                handle.write(content)
    if not pending:
        print("Starter files already match; no changes")
    elif not apply:
        print("Preview only; add --apply to write these files")
    if (target / adoption.LOCK).exists():
        manifest = adoption.load_manifest(target)
        revision = manifest["source_revision"]
        origin = manifest.get("source_revision_origin", "unrecorded")
    else:
        revision, origin = adoption.source_provenance(SKILL, source_revision)
    print(f"Source revision: {revision or 'unknown'} ({origin})")
    if origin == "supplied":
        print("Supplied provenance; not verified against source Git bytes")
    elif revision is None:
        print("Exact upstream revision unknown; generated byte hashes are still recorded")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("target", type=Path)
    parser.add_argument("--owner", required=True)
    parser.add_argument("--apply", action="store_true")
    parser.add_argument("--source-revision", help="Supplied upstream SHA (40 hex; not Git-verified)")
    args = parser.parse_args()
    try:
        bootstrap(args.target, args.owner, args.apply, args.source_revision)
    except (OSError, ValueError) as error:
        print(f"Ratpack: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
